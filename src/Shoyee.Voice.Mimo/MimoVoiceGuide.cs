using Shoyee.Voice;

namespace Shoyee.Voice.Mimo;

/// <summary>
/// 给模型看的 MiMo 语音手册（<c>voice_help</c> 的正文）。
///
/// 放在实现项目里是有意的：音色 id、<c>(风格)</c> 标签、<c>[叹气]</c> 音频标签都是 MiMo 的方言，
/// 换一家 TTS 就是另一套语法。工具层只负责把 <see cref="ISpeechSynthesizer.VoiceGuide"/> 原样交出去。
/// </summary>
internal static class MimoVoiceGuide
{
    /// <summary>手册正文。</summary>
    public const string Text = """
        MiMo 语音合成（mimo-v2.5-tts 系列）用法

        voice_speak 参数：
        - text：要合成的文本（必填）
        - style：自然语言风格指令（可选），如「温柔一点，语速稍慢」「压着嗓子，像在密谋」
        - voice：音色 id（可选），不传用配置里的默认音色

        风格有两种写法，位置不同：
        1) 风格标签写在 text 开头：(风格1 风格2)正文。括号 () （） [] 都行。
           常用：开心 悲伤 愤怒 兴奋 委屈 平静 冷漠 / 怅然 欣慰 无奈 愧疚 释然 嫉妒 忐忑 动情 /
                 温柔 高冷 活泼 严肃 慵懒 俏皮 深沉 干练 凌厉 / 磁性 醇厚 清亮 空灵 稚嫩 苍老 甜美 沙哑 /
                 夹子音 御姐音 正太音 大叔音 / 东北话 四川话 河南话 粤语
           例：(慵懒)再让我睡五分钟……就五分钟。
        2) 音频标签插在正文任意位置：[叹气] [轻笑] [哽咽] [深呼吸] [语速加快] 之类，控制顿挫与情绪。
           例：（极其疲惫）师傅……到地方了叫我一声……[长叹一口气] 我先眯一会儿。

        预置音色（voice 参数）：mimo_default（默认）、冰糖、茉莉、苏打、白桦、Mia、Chloe、Milo、Dean。
        其中 冰糖/茉莉 女声中文，苏打/白桦 男声中文，其余英文。

        注意事项：
        - 标签是给声音的提示，不要和正文语义打架（「开心」配一段哭诉会很怪）。
        - 一段话里别堆太多标签，情绪转折处用一个就够。
        - 合成文本要贴合音色：温柔治愈系配晚安独白，不要配体育解说。
        - 工作区若配置了 designPrompt，则以音色设计模型为准，voice 参数会被忽略。
        """;
}
