    /// <summary>来源渠道名。</summary>
    public string? Channel
    {
        get => GetValue(ChannelProperty);
        set => SetValue(ChannelProperty, value);
    }

    /// <inheritdoc />
    public override void Render(DrawingContext context)
    {
        var icon = Pick(Channel);
        var size = Math.Min(Bounds.Width, Bounds.Height);
        if (size <= 0 || icon.Bounds.Width <= 0 || icon.Bounds.Height <= 0)
        {
            return;
        }

        var inset = size * 0.08;
        var target = new Rect(inset, inset, size - inset * 2, size - inset * 2);
        var source = icon.Bounds;
        var scale = Math.Min(target.Width / source.Width, target.Height / source.Height);
        var dx = target.Center.X - source.Center.X * scale;
        var dy = target.Center.Y - source.Center.Y * scale;

        using (context.PushTransform(Matrix.CreateScale(scale, scale) * Matrix.CreateTranslation(dx, dy)))
        {
            foreach (var part in icon.Parts)
            {
                context.DrawGeometry(part.Brush, null, part.Geometry);
            }
        }
    }

    private static IconDrawing Pick(string? channel)
    {
        if (channel is not null
            && channel.StartsWith("Mattermost", StringComparison.OrdinalIgnoreCase))
        {
            return Mattermost;
        }

        if (channel is not null
            && (channel.Contains("微信", StringComparison.Ordinal)
                || channel.StartsWith("weixin", StringComparison.OrdinalIgnoreCase)))
        {
            return WeChat;
        }

        return Finder;
    }

    private static IconDrawing Create(params (string Data, string Fill)[] source)
    {
        var parts = new IconPart[source.Length];
        var left = double.MaxValue;
        var top = double.MaxValue;
        var right = double.MinValue;
        var bottom = double.MinValue;

        for (var i = 0; i < source.Length; i++)
        {
            var geometry = Geometry.Parse(source[i].Data);
            parts[i] = new IconPart(geometry, new SolidColorBrush(Color.Parse(source[i].Fill)));

            var bounds = geometry.Bounds;
            left = Math.Min(left, bounds.Left);
            top = Math.Min(top, bounds.Top);
            right = Math.Max(right, bounds.Right);
            bottom = Math.Max(bottom, bounds.Bottom);
        }

        return new IconDrawing(parts, new Rect(left, top, right - left, bottom - top));
    }

    private sealed record IconPart(Geometry Geometry, IBrush Brush);

    private sealed record IconDrawing(IReadOnlyList<IconPart> Parts, Rect Bounds);
